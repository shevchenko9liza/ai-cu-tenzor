import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const lab=path.join(root,'lab05');
let html=fs.readFileSync(path.join(lab,'prototype.template.html'),'utf8');
// Only the already cropped, published diagrams may enter the standalone file.
const diagrams=[
  ['location','pdu-scheme.png','39c4de1f3a9d91de82c777230600ac1177702034cf13734976761884de9ec271'],
  ['parameters','pen-ab-scheme.png','46ad4e11000e1c47f3bf0a03a01e42dd94af988f5e526250a69da6c9cd185955']
];
const images={};
for(const [key,file,expected] of diagrams){
  const bytes=fs.readFileSync(path.join(lab,'assets',file));
  if(crypto.createHash('sha256').update(bytes).digest('hex')!==expected)throw new Error('Review cropped diagram before embedding: '+file);
  images[key]='data:image/png;base64,'+bytes.toString('base64');
}
const logo='data:image/png;base64,'+fs.readFileSync(path.join(lab,'assets','tenzor-logo.png')).toString('base64');
if(!html.includes('__TENZOR_LOGO__'))throw new Error('Missing embedded logo marker');
html=html.replaceAll('__TENZOR_LOGO__',logo);
const marker='<!-- EMBEDDED_SCHEMES -->';
if(!html.includes(marker))throw new Error('Missing diagram embedding marker');
html=html.replace(marker,()=>`<script id="embedded-scheme-data">const SCHEME_IMAGES=${JSON.stringify(images)};</script>`);
for(const file of ['vendor/three.min.js','pump-view.js','decision-support.js']){
  const tag=`<script src="${file}"></script>`;
  if(!html.includes(tag))throw new Error('Missing script marker: '+file);
  const source=fs.readFileSync(path.join(lab,file),'utf8').replace(/<\/script/gi,'<\\/script');
  html=html.replace(tag,()=>`<script data-embedded-source="${file}">\n${source}\n</script>`);
}
const license=fs.readFileSync(path.join(lab,'vendor/THREE-LICENSE.txt'),'utf8');
html=html.replace('<head>',()=>`<head><!-- Generated by scripts/build-prototype.mjs. Edit prototype.template.html and the source JS files. -->\n<!-- Three.js license\n${license.replaceAll('--','—')}\n-->`);
fs.writeFileSync(path.join(lab,'prototype.html'),html);
console.log(`Standalone prototype: ${Buffer.byteLength(html)} bytes; 2 embedded diagrams + logo, 3 embedded scripts, no sibling runtime files required.`);
