import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const context=vm.createContext({Intl});
vm.runInContext(fs.readFileSync(new URL('../lab05/decision-support.js',import.meta.url),'utf8')+'\nthis.model=Support;',context);
const model=context.model;
const f=model.forecast(5.5);
assert.equal(f.state,'ok');
assert.equal(f.high,72);
assert.ok(f.low>30&&f.low<50);
assert.equal(model.vibration.length,25);
assert.equal(model.vibration[0],2.2);
assert.equal(model.vibration.at(-1),4.4);
assert.equal(model.forecast(4.4).state,'reached');
assert.equal(model.forecast(4).state,'reached');
assert.equal(model.forecast(5.5,true).state,'blocked');
for(const limit of [0,-2,21,NaN,Infinity])assert.equal(model.forecast(limit).state,'invalid');
const base=model.economics({...model.defaults});
assert.equal(base.unplanned,2100);
assert.equal(base.planned,830);
assert.equal(base.difference,1270);
assert.equal(base.hours,8);
assert.equal(base.expected,null);
assert.equal(model.economics({...model.defaults,probability:0}).expected,-830);
assert.equal(model.economics({...model.defaults,probability:100}).expected,1270);
assert.equal(model.economics({...model.defaults,probability:50}).expected,220);
assert.equal(model.economics({...model.defaults,hourCost:0}).difference,470);
assert.equal(model.economics({...model.defaults,plannedRepair:2000}).difference,-380);
assert.equal(model.economics({...model.defaults,unplannedHours:0,unplannedRepair:0}).breakEven,null);
for(const value of ['',-1,NaN,Infinity,1e8])assert.ok(model.economics({...model.defaults,hourCost:value}).error);
for(const value of [-1,101,NaN,Infinity])assert.ok(model.economics({...model.defaults,probability:value}).error);
console.log(JSON.stringify({status:'PASS',forecastHours:[f.low,f.high],unplanned:base.unplanned,planned:base.planned,difference:base.difference,units:'thousand RUB',cases:'forecast boundaries, blockers, cost algebra, zero reserve loss, negative benefit, missing inputs and probability'}));
